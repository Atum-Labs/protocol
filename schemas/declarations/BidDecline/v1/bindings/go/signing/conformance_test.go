package biddecline

import (
	"bytes"
	"encoding/json"
	"flag"
	"os"
	"regexp"
	"testing"
)

// goldenRelPath is the cross-language golden every implementation asserts, settler included.
const goldenRelPath = "../../../conformance/content-hash-golden.json"

// catalogRelPath and protoRelPath are read to prove every decline reason has a vector.
const (
	catalogRelPath = "../../../../../../apis/decline/v1/catalog.json"
	protoRelPath   = "../../../../../../apis/settler-gateway/v1/session-stream/settler.proto"
)

var update = flag.Bool("update", false, "rewrite the golden from goldenVectors")

const (
	paymentID = "0x1234abcd5678ef901234abcd5678ef901234abcd5678ef901234abcd5678ef90"
	issuedAt  = "2026-10-13T12:00:00.000Z"
)

// reasonCodes is every catalog code; TestConformance_CoversEveryReason keeps it complete.
var reasonCodes = []string{
	"UNSPECIFIED", "DEADLINE_TOO_SHORT", "NO_SETTLEMENT_HORIZON", "AUCTION_CLOSED", "QUOTE_INVALID",
	"DRAINING", "HOOK_DECLINED", "INTERNAL", "INSUFFICIENT_LIQUIDITY", "UNTRUSTED_VERIFIER",
	"AGENT_NOT_READY", "UNSUPPORTED_DESTINATION_ASSET", "QUOTE_GENERATION_FAILED", "AWARD_WINDOW_TOO_SHORT",
	"QUOTE_WINDOW_TOO_LONG", "SETTLER_UNSUPPORTED_ESCROW", "VERIFIER_UNSUPPORTED_ESCROW",
	"MAX_SOURCE_AMOUNT_TOO_LOW", "QUOTE_WINDOW_TOO_SHORT", "ASSET_PAUSED", "DESTINATION_ACCOUNT_RESTRICTED",
}

type vector struct {
	name string
	doc  map[string]string
}

func base() map[string]string {
	return map[string]string{
		"payment_id":       paymentID,
		"quote_request_id": "",
		"reason_code":      "DEADLINE_TOO_SHORT",
		"message":          "remaining fulfillment window 42s is below the 120s minimum",
		"issued_at":        issuedAt,
	}
}

func with(over map[string]string) map[string]string {
	m := base()
	for k, v := range over {
		m[k] = v
	}
	return m
}

func goldenVectors() []vector {
	var vs []vector
	for _, code := range reasonCodes {
		vs = append(vs, vector{"reason-" + code, with(map[string]string{"reason_code": code, "message": "declined: " + code})})
	}
	return append(vs,
		vector{"quote-request-flow", with(map[string]string{"payment_id": "", "quote_request_id": "qr-7f3e2a91-4b6c-4d1e-9a8f-2c5b7e9d0f13"})},
		vector{"empty-message", with(map[string]string{"message": ""})},
		vector{"non-ascii-message", with(map[string]string{
			"reason_code": "INSUFFICIENT_LIQUIDITY",
			"message":     "solde insuffisant — 残高不足 🚫 \"USDC\"\n newline \\ backslash",
		})},
		vector{"control-chars-message", with(map[string]string{
			"reason_code": "INTERNAL",
			"message":     "cr\r bell\u0007 del\u007f nul\u0000",
		})},
	)
}

type goldenCase struct {
	Name        string          `json:"name"`
	Declaration json.RawMessage `json:"declaration"`
	ContentHash string          `json:"content_hash"`
}

type goldenFile struct {
	Comment    string       `json:"_comment"`
	ContextURL string       `json:"context_url"`
	Cases      []goldenCase `json:"cases"`
}

func marshalDoc(t *testing.T, fields map[string]string) json.RawMessage {
	t.Helper()
	doc := map[string]any{"@context": []string{ContextURL}}
	for k, v := range fields {
		doc[k] = v
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(doc); err != nil {
		t.Fatal(err)
	}
	return json.RawMessage(bytes.TrimSpace(buf.Bytes()))
}

func writeGolden(t *testing.T) {
	t.Helper()
	g := goldenFile{
		Comment: "Frozen cross-language content-hash vectors for the BidDecline/v1 declaration. Generated by the Go binding " +
			"(make -C bindings/go/signing gen-conformance), never edited by hand. Every implementation (protocol Go and TypeScript, " +
			"the settler's own port) recomputes content_hash from declaration and asserts equality.",
		ContextURL: ContextURL,
	}
	for _, v := range goldenVectors() {
		raw := marshalDoc(t, v.doc)
		h, err := ComputeBidDeclineHash(raw)
		if err != nil {
			t.Fatalf("%s: %v", v.name, err)
		}
		g.Cases = append(g.Cases, goldenCase{Name: v.name, Declaration: raw, ContentHash: h})
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(g); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(goldenRelPath, buf.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
}

func loadGolden(t *testing.T) goldenFile {
	t.Helper()
	raw, err := os.ReadFile(goldenRelPath)
	if err != nil {
		t.Fatalf("read golden: %v", err)
	}
	var g goldenFile
	if err := json.Unmarshal(raw, &g); err != nil {
		t.Fatalf("unmarshal golden: %v", err)
	}
	if len(g.Cases) == 0 {
		t.Fatal("golden has no cases")
	}
	return g
}

func TestConformance_Golden(t *testing.T) {
	if *update {
		writeGolden(t)
	}
	g := loadGolden(t)
	if g.ContextURL != ContextURL {
		t.Fatalf("golden context_url %q != ContextURL %q", g.ContextURL, ContextURL)
	}
	if len(g.Cases) != len(goldenVectors()) {
		t.Fatalf("golden has %d cases, code defines %d: run make gen-conformance", len(g.Cases), len(goldenVectors()))
	}
	for _, c := range g.Cases {
		got, err := ComputeBidDeclineHash(c.Declaration)
		if err != nil {
			t.Fatalf("%s: %v", c.Name, err)
		}
		if got != c.ContentHash {
			t.Errorf("%s: content_hash = %s, golden = %s", c.Name, got, c.ContentHash)
		}
	}
}

// Every catalog code and every DeclineReason proto value except UNSPECIFIED must have a vector.
func TestConformance_CoversEveryReason(t *testing.T) {
	seen := map[string]bool{}
	for _, c := range loadGolden(t).Cases {
		var d struct {
			ReasonCode string `json:"reason_code"`
		}
		if err := json.Unmarshal(c.Declaration, &d); err != nil {
			t.Fatalf("%s: %v", c.Name, err)
		}
		seen[d.ReasonCode] = true
	}

	rawCatalog, err := os.ReadFile(catalogRelPath)
	if err != nil {
		t.Fatalf("read catalog: %v", err)
	}
	var catalog struct {
		Entries map[string]json.RawMessage `json:"entries"`
	}
	if err := json.Unmarshal(rawCatalog, &catalog); err != nil {
		t.Fatalf("unmarshal catalog: %v", err)
	}
	if len(catalog.Entries) == 0 {
		t.Fatal("catalog has no entries")
	}
	for code := range catalog.Entries {
		if !seen[code] {
			t.Errorf("no golden vector for catalog code %s", code)
		}
	}

	proto, err := os.ReadFile(protoRelPath)
	if err != nil {
		t.Fatalf("read settler.proto: %v", err)
	}
	re := regexp.MustCompile(`(?m)^\s*DECLINE_REASON_([A-Z0-9_]+)\s*=`)
	found := 0
	for _, m := range re.FindAllStringSubmatch(string(proto), -1) {
		found++
		if !seen[m[1]] {
			t.Errorf("no golden vector for DECLINE_REASON_%s", m[1])
		}
	}
	if found == 0 {
		t.Fatal("found no DeclineReason values in settler.proto")
	}
}

// The reverse of TestConformance_CoversEveryReason: a vector for a code the catalog or
// the DeclineReason enum does not define is a frozen hash no settler can ever emit, and
// usually means a reason was added to the vectors but never shipped in the contract.
func TestConformance_EveryReasonVectorIsARealReason(t *testing.T) {
	rawCatalog, err := os.ReadFile(catalogRelPath)
	if err != nil {
		t.Fatalf("read catalog: %v", err)
	}
	var catalog struct {
		Entries map[string]json.RawMessage `json:"entries"`
	}
	if err := json.Unmarshal(rawCatalog, &catalog); err != nil {
		t.Fatalf("unmarshal catalog: %v", err)
	}

	proto, err := os.ReadFile(protoRelPath)
	if err != nil {
		t.Fatalf("read settler.proto: %v", err)
	}
	inProto := map[string]bool{}
	re := regexp.MustCompile(`(?m)^\s*DECLINE_REASON_([A-Z0-9_]+)\s*=`)
	for _, m := range re.FindAllStringSubmatch(string(proto), -1) {
		inProto[m[1]] = true
	}
	if len(inProto) == 0 {
		t.Fatal("found no DeclineReason values in settler.proto")
	}

	for _, code := range reasonCodes {
		if _, ok := catalog.Entries[code]; !ok {
			t.Errorf("reasonCodes names %s but the catalog has no entry for it", code)
		}
		if !inProto[code] {
			t.Errorf("reasonCodes names %s but settler.proto has no DECLINE_REASON_%s", code, code)
		}
	}
}
