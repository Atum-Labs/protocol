// Package simplefold generates the TypeScript table of Go's Unicode simple-folding relation, so both
// bindings match JSON member names exactly as encoding/json does. JavaScript has no simple fold.
package simplefold

import (
	"fmt"
	"strings"
	"unicode"
)

// TypeScriptFile is the path of the generated table, relative to the Go module root.
const TypeScriptFile = "../../typescript/sender-auth/src/simple-fold.gen.ts"

// TypeScript returns the contents of the generated table.
func TypeScript() string {
	var pairs []string
	for r := rune(0); r <= unicode.MaxRune; r++ {
		least := r
		for f := unicode.SimpleFold(r); f != r; f = unicode.SimpleFold(f) {
			if f < least {
				least = f
			}
		}
		if least != r {
			pairs = append(pairs, fmt.Sprintf("0x%x, 0x%x", r, least))
		}
	}

	var b strings.Builder
	b.WriteString("// Code generated by `go run ./cmd/gen-simple-fold` in bindings/go/sender-auth. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "/** Unicode version of the Go tables this was generated from. */\nexport const SIMPLE_FOLD_UNICODE_VERSION = %q;\n\n", unicode.Version)
	b.WriteString("/**\n")
	b.WriteString(" * Flattened [code point, least code point of its simple-folding orbit] pairs, ascending, for every\n")
	b.WriteString(" * code point that is not the least of its orbit.\n")
	b.WriteString(" */\n")
	b.WriteString("export const SIMPLE_FOLD_PAIRS: readonly number[] = [\n")
	for i := 0; i < len(pairs); i += 6 {
		end := min(i+6, len(pairs))
		b.WriteString("  " + strings.Join(pairs[i:end], ", ") + ",\n")
	}
	b.WriteString("];\n")
	return b.String()
}
