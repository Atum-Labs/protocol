// directDepositVectorFile is conformance/direct-deposit-derivation-vectors.json: what
// DeriveDirectDeposit returns for each request, for the TypeScript suite to assert. The golden
// "known answer" row is the contract's own vector (TestDeriveDirectDepositReproducesTheKnownAnswer).
type directDepositVectorFile struct {
	Comment string                 `json:"_comment"`
	Golden  []directDepositGolden  `json:"golden"`
	Refused []directDepositRefused `json:"refused"`
}

type directDepositGolden struct {
	Name               string `json:"name"`
	Request            string `json:"request"`
	ChainID            string `json:"chainId"`
	Escrow             string `json:"escrow"`
	Version            int    `json:"version"`
	DepositID          string `json:"depositId"`
	Token              string `json:"token"`
	Amount             string `json:"amount"`
	Nonce              string `json:"nonce"`
	DepositRequestHash string `json:"depositRequestHash"`
	Destination        string `json:"destination"`
	Reserver           string `json:"reserver"`
	Releaser           string `json:"releaser"`
	UnreservedHash     string `json:"unreservedHash"`
}

type directDepositRefused struct {
	Name    string `json:"name"`
	Request string `json:"request"`
	ChainID string `json:"chainId"`
	Escrow  string `json:"escrow"`
	Version int    `json:"version"`
	Reason  string `json:"reason"`
}

func directDepositVectors(t *testing.T) directDepositVectorFile {
	t.Helper()
	file := directDepositVectorFile{
		Comment: "DeriveDirectDeposit (Go senderauth/direct_deposit.go) for each request; the TypeScript deriveDirectDeposit (sender-auth/src/direct-deposit.ts) must return the same. " +
			"Generated by Go: REGEN_DIRECT_DEPOSIT_VECTORS=1 go test -count=1 ./senderauth. The \"known answer\" row is contracts/evm/conformance/direct-deposit-vectors.json, which the real Escrow pins.",
	}
	wrongChecksum := func(d map[string]any) {
		d["quote_selector"] = "0x9139213Be0cF31C8B1bD609f1d953605e20bD2Cb"
		d["source"].(map[string]any)["account"] = "0x00000000000000000000000000000000000a11CE"
		d["source"].(map[string]any)["asset_identifier"] = "eip155:31337/erc20:0x00000000000000000000000000000000000070cE"
		d["fulfillment_verifier"].(map[string]any)["account"] = "0x83743F550bcdb5bE905766E2E3CB9a86c6823cC9"
	}
	// The request exactly as the payment-gateway client's prepareDirectDepositRequest builds it
	// (payment-gateway-client prepare-direct-deposit.test.ts reproduces these rows through it):
	// the current version, millisecond deadlines, a 40-hex EIP-3009 destination and a
	// fulfillment_proxy, none of which the rows above carry. The request_id is a version 4 UUID,
	// the only id the client admits at version 1.
	sdkShaped := func(d map[string]any) {
		d["version"] = "1.3"
		d["request_id"] = "6b1e4d2a-8c3f-4e5b-9a7d-2f0c8e1b3d54"
		d["destination"] = []any{map[string]any{
			"asset_identifier": "eip155:8453/erc20:0x833589fCD6eDb6E08f4c7C32D4f71b54bdA02913",
			"account":          "0x000000000000000000000000000000000000b0b0",
		}}
		d["quote_deadline"] = "2030-01-01T00:00:00.000Z"
		d["fulfillment_deadline"] = "2030-01-01T00:10:00.000Z"
		d["fulfillment_proxy"] = "0x000000000000000000000000000000000000f0f0"
	}
	goldens := []struct {
		name    string
		edit    func(map[string]any)
		version DirectDepositHashVersion
	}{
		{"known answer (v1)", nil, DirectDepositHashV1},
		{"known answer request under v2", nil, DirectDepositHashV2},
		{"another nonce (v1)", func(d map[string]any) { d["deposit_nonce"] = "8" }, DirectDepositHashV1},
		{"a nonce with leading zeros (v1)", func(d map[string]any) { d["deposit_nonce"] = "007" }, DirectDepositHashV1},
		// The escrow takes nonce 0 like any other: it is bit 0 of the owner's first bitmap word.
		{"nonce zero (v1)", func(d map[string]any) { d["deposit_nonce"] = "0" }, DirectDepositHashV1},
		{"another fulfillment_amount (v2)", func(d map[string]any) { d["fulfillment_amount"] = "750001" }, DirectDepositHashV2},
		{"another quote_deadline (v2)", func(d map[string]any) { d["quote_deadline"] = "2030-01-01T00:01:00Z" }, DirectDepositHashV2},
		// Addresses are read case-insensitively, as the escrow does: a mixed-case address whose
		// EIP-55 checksum is wrong names the same account, so under v1 the id is the known answer's.
		{"mixed-case addresses with a wrong checksum (v1)", wrongChecksum, DirectDepositHashV1},
		// Under v2 the hash commits the address strings as written, so the same spelling is another
		// depositRequestHash, and another id than the known answer's under v2.
		{"mixed-case addresses with a wrong checksum (v2)", wrongChecksum, DirectDepositHashV2},
		{"sdk-shaped request (v1)", sdkShaped, DirectDepositHashV1},
		{"sdk-shaped request (v2)", sdkShaped, DirectDepositHashV2},
	}
	for _, g := range goldens {
		request := vectorRequest(t, g.edit)
		got, err := DeriveDirectDeposit(request, vectorChainID, vectorEscrow, g.version)
		require.NoError(t, err, g.name)
		w := got.Input.DepositWitness
		file.Golden = append(file.Golden, directDepositGolden{
			Name: g.name, Request: string(request), ChainID: vectorChainID.String(), Escrow: vectorEscrow.Hex(), Version: int(g.version),
			DepositID: got.ID.Hex(), Token: got.Input.Token.Hex(), Amount: got.Input.Amount.String(), Nonce: got.Input.Nonce.String(),
			DepositRequestHash: "0x" + hex.EncodeToString(w.DepositRequestHash[:]), Destination: w.Destination,
			Reserver: w.Reserver.Hex(), Releaser: w.Releaser.Hex(), UnreservedHash: got.UnreservedHash.Hex(),
		})
	}
	for _, r := range directDepositRefusals() {
		file.Refused = append(file.Refused, directDepositRefused{
			Name: r.name, Request: string(vectorRequest(t, r.edit)), ChainID: vectorChainID.String(), Escrow: r.escrowOf().Hex(),
			Version: int(r.version), Reason: r.reason,
		})
	}
	return file
}

func TestDirectDepositDerivationVectors_AreCurrent(t *testing.T) {
	fixture, err := json.MarshalIndent(directDepositVectors(t), "", "  ")
	require.NoError(t, err)
	fixture = append(asciiJSON(fixture), '\n')
	path := conformancePath("direct-deposit-derivation-vectors.json")
	if os.Getenv("REGEN_DIRECT_DEPOSIT_VECTORS") == "1" {
		require.NoError(t, os.WriteFile(path, fixture, 0o644))
	}
	committed, err := os.ReadFile(path)
	require.NoError(t, err)
	assert.Equal(t, string(fixture), string(committed), "direct-deposit-derivation-vectors.json is stale; regenerate it")
}
