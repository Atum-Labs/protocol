#!/usr/bin/env node
// Builds a CJS bundle (dist-cjs/lib.cjs) consumable by a CommonJS
// runtime. The ESM source uses `import.meta.url` (in canonicalize.ts) to
// find dist/contexts/ relative to the running file — esbuild's CJS
// bundling replaces `import.meta.url` with an empty object, so we ship a
// tiny wrapper (dist-cjs/index.js) that sets a
// `_PR_LD_SIGNING_CONTEXTS_DIR` env var BEFORE requiring the bundled lib.
// canonicalize.ts reads that env var first and falls back to
// import.meta.url for the native ESM consumers.
//
// External packages (ethers, jsonld, bs58, tweetnacl, the shared
// @atum-labs/ld-data-integrity lib) are marked external because they're
// declared as `dependencies` in package.json and resolved at runtime by
// the consumer's node_modules — bundling them would bloat the output and
// duplicate them in memory.

import { build } from "esbuild";
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

// bs58's CommonJS build exports its codec as `exports.default`. This package is "type": "module",
// so esbuild binds `import bs58 from "bs58"` to the whole CommonJS module, as Node would, and
// `bs58.encode` is undefined. The import goes through a shim that returns the codec; bs58 itself
// stays external.
const bs58Interop = {
  name: "bs58-interop",
  setup(b) {
    b.onResolve({ filter: /^bs58$/ }, (args) =>
      args.namespace === "bs58-interop"
        ? { path: "bs58", external: true }
        : { path: "bs58", namespace: "bs58-interop" },
    );
    b.onLoad({ filter: /.*/, namespace: "bs58-interop" }, () => ({
      contents: 'const m = require("bs58"); module.exports = m.default ?? m;',
      loader: "js",
    }));
  },
};

const __dirname = dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = resolve(__dirname, "..");
const OUT_DIR = resolve(PKG_ROOT, "dist-cjs");

mkdirSync(OUT_DIR, { recursive: true });

await build({
  entryPoints: [resolve(PKG_ROOT, "src/lib.ts")],
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node20",
  outfile: resolve(OUT_DIR, "lib.cjs"),
  external: [
    "ethers",
    "jsonld",
    "bs58",
    "tweetnacl",
    // Keep the shared TS lib external so it's resolved at
    // runtime via the consumer's node_modules (workspace symlink in
    // monorepo / installed package in CI). The lib's CJS bundle is
    // self-contained — it ships its own contexts/ + wrapper. Bundling
    // inline would force us to copy the lib's vendored contexts into this
    // CJS dir too, duplicating files across bundles.
    "@atum-labs/ld-data-integrity",
  ],
  define: {
    "import.meta.url": '"file:///__bundled_cjs__"',
  },
  plugins: [bs58Interop],
  logLevel: "warning",
});

const wrapper = `// Auto-generated by scripts/build-cjs.mjs.
//
// This wrapper used to set _PR_LD_SIGNING_CONTEXTS_DIR so the bundled loader could find the
// JSON-LD contexts shipped beside it. The contexts are now inlined into the code
// (src/contexts.generated.ts), so there is nothing to locate: they travel with the
// bundle through any consumer's bundler, and the override stays available for anyone
// who sets it deliberately.
//
// The assignment was removed rather than made conditional because it was
// UNCONDITIONAL, and once this bundle was inlined into a consumer it pointed at the
// CONSUMER's directory — overriding the embedded contexts with a path that does not
// exist there.
module.exports = require('./lib.cjs');
`;
writeFileSync(resolve(OUT_DIR, "index.js"), wrapper);

// Marker package.json so Node treats dist-cjs/*.js as CJS even when the
// root package.json declares "type": "module" for the ESM build.
writeFileSync(
  resolve(OUT_DIR, "package.json"),
  JSON.stringify({ type: "commonjs" }, null, 2) + "\n",
);

console.log("✅ dist-cjs/ build complete");
