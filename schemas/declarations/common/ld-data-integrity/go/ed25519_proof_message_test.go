// proofMessageVectors mirrors conformance/ed25519-proof-message.json, read by
// the Go and TS tests. Regenerate with REGEN_LD_PROOF_MESSAGE=1.
type proofMessageVectors struct {
	Comment string `json:"_comment"`
	Prefix  string `json:"prefix"`
	Vectors []struct {
		Name            string `json:"name"`
		SigningInputHex string `json:"signingInputHex"`
		Message         string `json:"message"`
	} `json:"vectors"`
	InvalidSigningInputLengths []int `json:"invalidSigningInputLengths"`
}

func proofMessageVectorsPath(t *testing.T) string {
	t.Helper()
	cwd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	return filepath.Join(cwd, "..", "conformance", "ed25519-proof-message.json")
}

func seqBytes(n int) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = byte(i)
	}
	return b
}

func TestEd25519ProofMessageConformance(t *testing.T) {
	path := proofMessageVectorsPath(t)
	if os.Getenv("REGEN_LD_PROOF_MESSAGE") == "1" {
		inputs := []struct {
			name string
			in   []byte
		}{
			{"zeros", make([]byte, 64)},
			{"ones", bytes.Repeat([]byte{0xff}, 64)},
			{"sequence", seqBytes(64)},
			{"url_alphabet", bytes.Repeat([]byte{0xfb, 0xff, 0xbf}, 22)[:64]},
		}
		out := proofMessageVectors{
			Comment:                    "Ed25519ProofMessage(signingInput) = prefix || base64url-nopad(signingInput). signingInput is the 64-byte proofHash||docHash of Ed25519Signature2020. Generated by REGEN_LD_PROOF_MESSAGE=1 go test -run TestEd25519ProofMessageConformance.",
			Prefix:                     Ed25519ProofMessagePrefix,
			InvalidSigningInputLengths: []int{0, 32, 63, 65},
		}
		for _, v := range inputs {
			msg, err := Ed25519ProofMessage(v.in)
			if err != nil {
				t.Fatal(err)
			}
			out.Vectors = append(out.Vectors, struct {
				Name            string `json:"name"`
				SigningInputHex string `json:"signingInputHex"`
				Message         string `json:"message"`
			}{v.name, hex.EncodeToString(v.in), string(msg)})
		}
		raw, err := json.MarshalIndent(out, "", "  ")
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, append(raw, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var f proofMessageVectors
	if err := json.Unmarshal(raw, &f); err != nil {
		t.Fatal(err)
	}
	if f.Prefix != Ed25519ProofMessagePrefix {
		t.Fatalf("prefix %q, want %q", f.Prefix, Ed25519ProofMessagePrefix)
	}
	if len(f.Vectors) == 0 {
		t.Fatal("no vectors")
	}
	for _, v := range f.Vectors {
		in, err := hex.DecodeString(v.SigningInputHex)
		if err != nil {
			t.Fatalf("%s: %v", v.Name, err)
		}
		got, err := Ed25519ProofMessage(in)
		if err != nil {
			t.Fatalf("%s: %v", v.Name, err)
		}
		if string(got) != v.Message {
			t.Errorf("%s: got %q, want %q", v.Name, got, v.Message)
		}
		if len(got) != 103 {
			t.Errorf("%s: len %d, want 103", v.Name, len(got))
		}
		for _, c := range got {
			if c < 0x20 || c > 0x7e {
				t.Errorf("%s: non printable byte 0x%02x", v.Name, c)
			}
		}
	}
	for _, n := range f.InvalidSigningInputLengths {
		if _, err := Ed25519ProofMessage(make([]byte, n)); !errors.Is(err, ErrMalformedProof) {
			t.Errorf("len %d: err %v, want ErrMalformedProof", n, err)
		}
	}
}

func TestVerifyEd25519Proof_AcceptsRawAndText(t *testing.T) {
	priv := ed25519.NewKeyFromSeed(make([]byte, 32))
	pub := priv.Public().(ed25519.PublicKey)
	in := make([]byte, 64)
	for i := range in {
		in[i] = byte(i)
	}
	text, err := Ed25519ProofMessage(in)
	if err != nil {
		t.Fatal(err)
	}
	for name, msg := range map[string][]byte{"raw": in, "text": text} {
		if err := VerifyEd25519Proof(pub, in, ed25519.Sign(priv, msg)); err != nil {
			t.Errorf("%s: %v", name, err)
		}
	}
	relabel := func(prefix string) []byte {
		return append([]byte(prefix), text[len(Ed25519ProofMessagePrefix):]...)
	}
	other := bytes.Clone(in)
	other[0] ^= 0xff
	otherText, err := Ed25519ProofMessage(other)
	if err != nil {
		t.Fatal(err)
	}
	for name, msg := range map[string][]byte{
		"another raw input":  other,
		"another text input": otherText,
		"truncated raw":      in[:63],
		"extended raw":       append(bytes.Clone(in), 0),
		"prefix and raw":     append([]byte(Ed25519ProofMessagePrefix), in...),
		"ld-proof v2 label":  relabel("atum ld-proof v2 "),
		"deposit label":      relabel("atum deposit v1 "),
		"release label":      relabel("atum release v1 "),
		"no label":           relabel(""),
		"proofHash half raw": in[:32],
	} {
		if err := VerifyEd25519Proof(pub, in, ed25519.Sign(priv, msg)); !errors.Is(err, ErrEd25519Verify) {
			t.Errorf("%s: err %v, want ErrEd25519Verify", name, err)
		}
	}
}
