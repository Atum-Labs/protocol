#!/usr/bin/env node
/**
 * Regenerates the determine-payment-id pipeline vector at
 * contracts/svm/bindings/go/escrow-encoding/encoding/testdata/test_vectors.json.
 *
 * SCOPE: this vector ONLY exercises the Go message_prehash pipeline
 * (JSON parse + Base58 decode of pubkeys + string amount parsing -> deposit_hash),
 * asserted by payment_id_determiner_test.go::TestDeterminePaymentID_CrossValidation.
 *
 * The deposit / reserve / release / refund hash spec is NOT validated here any
 * more. That parity is now anchored to the AUTHORITATIVE, program-sourced golden
 * at contracts/svm/conformance/parity-golden.json, produced by the on-chain
 * escrow program's own compute_*_hash functions (see
 * a FROZEN corpus of the pre-v3 layouts; its Rust harness no longer exists). The
 * Rust harness, the Go encoder (parity_golden_test.go), and the TS encoder
 * (parity-golden.test.ts) all assert against that one source of truth.
 *
 * Run this only if the message_prehash pipeline / test domain changes:
 *
 *   npm run build --workspace=@atum-labs/solana-escrow-encoding
 *   node contracts/svm/bindings/typescript/escrow-encoding/scripts/generate-test-vectors.mjs
 */

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import bs58module from 'bs58';

// bs58 ships both default and CJS namespace exports; resolve uniformly.
const bs58 = bs58module.default ?? bs58module;

import { Pubkey } from '../dist/pubkey.js';
import { computeDepositHash } from '../dist/deposit-encoder.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

function filledBytes(byte, length = 32) {
  return new Uint8Array(length).fill(byte);
}

function toHex(bytes) {
  return Array.from(bytes).map(b => b.toString(16).padStart(2, '0')).join('');
}

// Test domain — must match Go's testEscrowDomain() in test_helpers_test.go.
//   cluster_id              = ASCII "test" right-padded to 32 bytes
//   signature_domain_version = 1
//   program_id              = 0xAB * 32
// This domain is intentionally a fixed test fixture for the pipeline check; the
// authoritative hash spec lives in parity-golden.json (real program_id).
const clusterId = new Uint8Array(32);
clusterId.set(new TextEncoder().encode('test'));
const programIdBytes = filledBytes(0xab);
const domain = {
  clusterId,
  signatureDomainVersion: 1,
  programId: Pubkey.fromBytes(programIdBytes),
};

const depositRequestHash = filledBytes(0x01);
const depositorBytes = filledBytes(0x02);
const mintBytes = filledBytes(0x03);
const reserverBytes = filledBytes(0x04);
const releaserBytes = filledBytes(0x05);

const amount = 1_000_000n;
const nonce = 100n;
const issuedAt = 1_700_000_000n;
const deadline = 1_700_000_120n;

const depositHash = computeDepositHash(
  {
    depositRequestHash,
    depositor: Pubkey.fromBytes(depositorBytes),
    mint: Pubkey.fromBytes(mintBytes),
    amount,
    reserver: Pubkey.fromBytes(reserverBytes),
    releaser: Pubkey.fromBytes(releaserBytes),
    nonce,
    issuedAt,
    deadline,
  },
  domain,
);

const determinePaymentIDPrehash = JSON.stringify({
  // The FROZEN v1..=v3 prehash wire key. See SolanaDepositPrehash in payment_id_determiner.go:
  // the Go field carries the accurate name, but the wire key stays payment_id so existing
  // producers and the gateway keep parsing.
  payment_id: '0x' + toHex(depositRequestHash),
  depositor: bs58.encode(depositorBytes),
  mint: bs58.encode(mintBytes),
  amount: String(amount),
  reserver: bs58.encode(reserverBytes),
  releaser: bs58.encode(releaserBytes),
  nonce: String(nonce),
  issued_at: String(issuedAt),
  deadline: String(deadline),
});

const vectors = {
  _comment:
    'Generated by contracts/svm/bindings/typescript/escrow-encoding/scripts/generate-test-vectors.mjs - DO NOT EDIT MANUALLY. Re-run the script to regenerate. Scope: message_prehash pipeline only (Go JSON+Base58 parsing). The deposit/reserve/release/refund hash spec is validated against the program-sourced parity-golden.json, not this file.',
  domain: {
    cluster_id: toHex(clusterId),
    signature_domain_version: 1,
    program_id: toHex(programIdBytes),
  },
  determine_payment_id: {
    message_prehash: determinePaymentIDPrehash,
    expected_hash: toHex(depositHash),
  },
};

const out = resolve(
  __dirname,
  '..',
  '..',
  '..',
  'go',
  'escrow-encoding',
  'encoding',
  'testdata',
  'test_vectors.json',
);
writeFileSync(out, JSON.stringify(vectors, null, 2) + '\n');
console.log('wrote', out);
