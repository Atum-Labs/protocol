import { describe, it, expect } from 'vitest';
import { Pubkey } from './pubkey';
import { EscrowDomain } from './escrow-domain';
import {
  EscrowDepositParams,
  computeDepositHash,
  computeDepositHashV2,
  computeDestinationHash,
  MAX_DESTINATION_LEN,
} from './deposit-encoder';
import { computeReserveHashV2 } from './reserve-encoder';
import { computeReleaseHashV2 } from './release-encoder';
import { computeRefundHashV2 } from './refund-encoder';
import {
  EmptyDestinationError,
  DestinationTooLongError,
  ZeroQuoteHashError,
} from './errors';

/**
 * These anchors are NOT produced by this package. Each was derived out of band with an independent
 * keccak-256 (foundry `cast keccak`) from the documented preimage layout, and each is the identical
 * literal the on-chain Rust program and the Go encoder pin for the same inputs.
 *
 * That shared-literal property is the entire point. A corpus generated by one implementation and checked
 * by the others only proves they agree with the generator; three implementations independently pinned to
 * one out-of-band value proves all three match the spec. If any single side drifts, exactly that side
 * starts failing.
 */

// The escrow program's declared ID, 44DjKbs1uV3uq26HjJLY67EXuVvwCbBoSUC2tDBWbkrs, as raw hex so no
// base58 decoder sits in the derivation path.
const PROGRAM_ID_HEX = '2d66325a159b21433ca818ab4b70519d166c8c9684ddd218637147896c012238';
// So11111111111111111111111111111111111111112 (wSOL) — depositor.
const DEPOSITOR_HEX = '069b8857feab8184fb687f634618c035dac439dc1aeb3b5598a0f00000000001';
// EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v (USDC mint) — mint.
const MINT_HEX = 'c6fa7af3bedbad3a3d65f36aabc97431b1bbe4c2d2f6e0e47ca60203452f5d61';

/** The ratified canonical destination form: `<CAIP-19 asset>@<account>`, 103 bytes. */
const DESTINATION =
  'eip155:8453/erc20:0x833589fcd6edb6e08f4c7c32d4f71b54bda02913@0xc0ffee254729296a45a3885639ac7e10f9d54979';

/**
 * keccak256(DESTINATION). Byte-identical to the value EVM and TVM pin for the same canonical string —
 * that cross-VM equality is the whole point of committing to a plaintext destination.
 */
const DESTINATION_HASH_HEX = '7e096a6d1abcfc4daab28cec3f3d3a458c3facbfa0f3493284bb891bdc9807ef';

/** Matches the program's ANCHOR_DEPOSIT_V4_DEVNET and Go's v4AnchorDepositDevnet. */
const ANCHOR_DEPOSIT_V4_DEVNET =
  '434c316fefd017642e55c0c037c8848d753ccb5449fac1292b15752c3f34b5f8';

/** The same inputs with the destination fed in RAW instead of hashed — the unsound value. */
const ANCHOR_DEPOSIT_V4_RAW_DESTINATION_FED =
  'd36b4a6aaacb3ba72c68039cccef9977ff2f231aa5608b9f1a7ab9ff2eeca4ed';

/**
 * The domain-version-3 quote-hash anchors, derived out of band from the documented layout. Inputs:
 * cluster "test", the real program ID, version 3, deposit_hash 0x11, recipient 0x22, quote_hash 0x33.
 * Identical to the literals Go pins in TestSolanaV2QuoteHashLayout. The program reproduces the
 * release and refund values in `contracts/svm/source/programs/escrow/tests/encoder_anchors.rs`.
 * The reserve value is the retired layout (no `source_amount`); the current reserve anchor is
 * pinned in `v5-source-amount.test.ts`.
 */
const ANCHOR_RESERVE_V3 = 'c9eaa290e13b1f46e72025806e6770494b324697d91bd844531dbfa1e84957ec';
const ANCHOR_RELEASE_V3 = 'f36c58efe96114e152ea68242ae176d6d0915155db834596b437ff90403b422d';
const ANCHOR_REFUND_V3 = '749ed0f68c7e49b52dca8479aa0dfb9a61d355754fb6ed2ff432a2367175f594';

/** The same release and refund inputs at domain version 5, the version the program stamps today. */
const ANCHOR_RELEASE_V5 = '64d43a5fa2dd3cfa93bb47fb00affffb3dfaa1597174d3de2b646f34ae5c57fe';
const ANCHOR_REFUND_V5 = '584a935d3088e3f30b1a47a4ac453f9a15f190b0a069781f69804af5a0995123';

function hexToBytes(hex: string): Uint8Array {
  const out = new Uint8Array(hex.length / 2);
  for (let i = 0; i < out.length; i++) {
    out[i] = parseInt(hex.slice(i * 2, i * 2 + 2), 16);
  }
  return out;
}

function toHex(bytes: Uint8Array): string {
  return Array.from(bytes)
    .map((b) => b.toString(16).padStart(2, '0'))
    .join('');
}

function filled(byte: number): Uint8Array {
  return new Uint8Array(32).fill(byte);
}

function clusterId(name: string): Uint8Array {
  const out = new Uint8Array(32);
  out.set(new TextEncoder().encode(name));
  return out;
}

/** The domain the v4 deposit anchor was derived against. */
function devnetV4Domain(): EscrowDomain {
  return {
    clusterId: clusterId('devnet'),
    signatureDomainVersion: 4,
    programId: new Pubkey(hexToBytes(PROGRAM_ID_HEX)),
  };
}

/** The domain the v3 quote-hash anchors were derived against. */
function testV3Domain(): EscrowDomain {
  return {
    clusterId: clusterId('test'),
    signatureDomainVersion: 3,
    programId: new Pubkey(hexToBytes(PROGRAM_ID_HEX)),
  };
}

function depositParams(): EscrowDepositParams {
  return {
    depositRequestHash: filled(0x44),
    depositor: new Pubkey(hexToBytes(DEPOSITOR_HEX)),
    mint: new Pubkey(hexToBytes(MINT_HEX)),
    amount: 1_000_000n,
    reserver: new Pubkey(filled(0x55)),
    releaser: new Pubkey(filled(0x66)),
    nonce: 0x0000_0001_0000_0007n, // bucket 1, slot 7
    issuedAt: 1_700_000_000n,
    deadline: 1_700_000_128n, // + REPLAY_HORIZON_SECS
  };
}

describe('destination commitment (domain version 4)', () => {
  it('hashes the destination to the cross-VM value', () => {
    // Worth asserting separately from the deposit anchor: this is the one value that must be
    // byte-identical across EVM, TVM and SVM for the same string, so a drift here should fail with an
    // unambiguous message rather than as an opaque deposit-hash mismatch.
    expect(toHex(computeDestinationHash(DESTINATION))).toBe(DESTINATION_HASH_HEX);
  });

  it('reproduces the on-chain program deposit anchor', () => {
    const got = computeDepositHashV2(depositParams(), DESTINATION, devnetV4Domain());
    expect(toHex(got)).toBe(ANCHOR_DEPOSIT_V4_DEVNET);
  });

  it('hashes the destination rather than feeding it raw', () => {
    // keccak256 concatenates without length prefixes, so injectivity depends on every hashed field
    // being fixed-width. Asserting only the positive anchor would not catch a raw feed reintroduced
    // alongside a regenerated anchor; requiring the result to DIFFER from the known unsound value is
    // what closes that hole.
    const got = computeDepositHashV2(depositParams(), DESTINATION, devnetV4Domain());
    expect(toHex(got)).not.toBe(ANCHOR_DEPOSIT_V4_RAW_DESTINATION_FED);
  });

  it('makes the destination load-bearing', () => {
    const domain = devnetV4Domain();
    const base = computeDepositHashV2(depositParams(), DESTINATION, domain);

    // A one-character change to the account's last nibble must change the hash.
    const altered = DESTINATION.slice(0, -1) + '8';
    expect(toHex(computeDepositHashV2(depositParams(), altered, domain))).not.toBe(toHex(base));

    // And it must differ from the frozen V1 layout, which commits to no destination at all.
    expect(toHex(computeDepositHash(depositParams(), domain))).not.toBe(toHex(base));
  });

  it('preserves base58 casing instead of normalising it', () => {
    // The ratified rule lowercases hex segments but preserves base58 byte-for-byte, because base58 is
    // case-significant: a blanket-lowercased Solana mint or account is a DIFFERENT address. The encoder
    // must not normalise, which is what keeps the rule enforceable off-chain rather than silently
    // corrupting Solana destinations.
    const solana =
      'solana:5eykt4UsFv8P8NJdTREpY1vzqKqZKvdp/token:EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v@9WzDXwBbmkg8ZTbNMqUxvQRAyrZzDsGYdLVL9zYtAWWM';
    const domain = devnetV4Domain();

    const asIs = computeDepositHashV2(depositParams(), solana, domain);
    const lowered = computeDepositHashV2(depositParams(), solana.toLowerCase(), domain);
    expect(toHex(asIs)).not.toBe(toHex(lowered));
  });

  it('enforces the destination bounds', () => {
    const domain = devnetV4Domain();
    expect(() => computeDepositHashV2(depositParams(), '', domain)).toThrow(EmptyDestinationError);

    const atLimit = 'a'.repeat(MAX_DESTINATION_LEN);
    expect(() => computeDepositHashV2(depositParams(), atLimit, domain)).not.toThrow();

    const overLimit = 'a'.repeat(MAX_DESTINATION_LEN + 1);
    expect(() => computeDepositHashV2(depositParams(), overLimit, domain)).toThrow(
      DestinationTooLongError,
    );
  });

  it('bounds the destination by UTF-8 bytes, not UTF-16 code units', () => {
    // The program bounds the UTF-8 encoding. A destination of MAX_DESTINATION_LEN multi-byte characters
    // is well under the limit by string length but far over it in bytes; measuring the wrong one lets
    // the client sign something the program rejects.
    const domain = devnetV4Domain();
    const multibyte = 'é'.repeat(MAX_DESTINATION_LEN); // 2 bytes each
    expect(multibyte.length).toBe(MAX_DESTINATION_LEN);
    expect(() => computeDepositHashV2(depositParams(), multibyte, domain)).toThrow(
      DestinationTooLongError,
    );
  });

  it('keeps the V1 deposit layout frozen', () => {
    // Adding the destination must not quietly redefine what domain versions 1..=3 signed; historical
    // deposits are still verified against the V1 layout.
    const got = computeDepositHash(depositParams(), devnetV4Domain());
    expect(toHex(got)).not.toBe(ANCHOR_DEPOSIT_V4_DEVNET);
  });
});

describe('quote-hash witnesses (domain version 3)', () => {
  const depositHash = filled(0x11);
  const recipient = new Pubkey(filled(0x22));
  const quoteHash = filled(0x33);

  it('reproduces the reserve anchor', () => {
    const got = computeReserveHashV2({ depositHash, recipient }, quoteHash, testV3Domain());
    expect(toHex(got)).toBe(ANCHOR_RESERVE_V3);
  });

  it('reproduces the release anchor', () => {
    const got = computeReleaseHashV2({ depositHash }, quoteHash, testV3Domain());
    expect(toHex(got)).toBe(ANCHOR_RELEASE_V3);
  });

  it('reproduces the refund anchor', () => {
    const got = computeRefundHashV2({ depositHash }, quoteHash, testV3Domain());
    expect(toHex(got)).toBe(ANCHOR_REFUND_V3);
  });

  it('rejects a zero quote hash at reserve but permits it at release and refund', () => {
    // The asymmetry is deliberate and mirrored from the Go encoder and the program: a reserve always
    // follows a quote, but a deposit can be refunded having never been reserved, in which case no quote
    // was ever bound to it. Collapsing these to one rule would either block legitimate refunds or let an
    // unquoted reserve through.
    const zero = filled(0x00);
    const domain = testV3Domain();

    expect(() => computeReserveHashV2({ depositHash, recipient }, zero, domain)).toThrow(
      ZeroQuoteHashError,
    );
    expect(() => computeReleaseHashV2({ depositHash }, zero, domain)).not.toThrow();
    expect(() => computeRefundHashV2({ depositHash }, zero, domain)).not.toThrow();
  });
});

describe('release and refund at the current domain version (5)', () => {
  const depositHash = filled(0x11);
  const quoteHash = filled(0x33);
  const domain: EscrowDomain = { ...testV3Domain(), signatureDomainVersion: 5 };

  it('reproduces the release anchor', () => {
    expect(toHex(computeReleaseHashV2({ depositHash }, quoteHash, domain))).toBe(ANCHOR_RELEASE_V5);
  });

  it('reproduces the refund anchor', () => {
    expect(toHex(computeRefundHashV2({ depositHash }, quoteHash, domain))).toBe(ANCHOR_REFUND_V5);
  });
});
