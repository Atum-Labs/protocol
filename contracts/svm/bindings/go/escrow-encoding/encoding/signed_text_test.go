// signed-text.json is FROZEN: Go and TS read it, and the program's inline pins in
// signatures.rs equal its hex. Regenerate only on an intentional format change:
//
//	REGEN_SIGNED_TEXT=1 go test ./... -run TestRegenerateSignedTextVectors
const signedTextVectorsPath = "../../../../conformance/signed-text.json"

const signedTextComment = "Escrow signed text `<label> <base64url-nopad(hash)>` and the exact bytes of its bare, v1 and v0 forms, " +
	"signed by the Ed25519 key derived from seed. Generated by signed_text_test.go (REGEN_SIGNED_TEXT=1); " +
	"read by the Go and TS escrow-encoding tests and pinned in programs/escrow/src/utils/signatures.rs. " +
	"nonCanonicalS holds a signature whose S was replaced by S+L, which strict verifiers reject."

type signedTextVector struct {
	Name    string `json:"name"`
	Label   string `json:"label"`
	Hash    string `json:"hash"`
	Text    string `json:"text"`
	Bare    string `json:"bare"`
	V1      string `json:"v1"`
	V0      string `json:"v0"`
	SigBare string `json:"sigBare"`
	SigV1   string `json:"sigV1"`
	SigV0   string `json:"sigV0"`
}

type signedTextNegative struct {
	Name      string `json:"name"`
	Message   string `json:"message"`
	Signature string `json:"signature"`
}

type signedTextFile struct {
	Comment       string               `json:"_comment"`
	Seed          string               `json:"seed"`
	PublicKey     string               `json:"publicKey"`
	Vectors       []signedTextVector   `json:"vectors"`
	NonCanonicalS []signedTextNegative `json:"nonCanonicalS"`
}

var signedTextSeed = func() []byte {
	s := make([]byte, 32)
	for i := range s {
		s[i] = byte(0xa0 + i)
	}
	return s
}()

func seqHash() [32]byte {
	var h [32]byte
	for i := range h {
		h[i] = byte(i)
	}
	return h
}

func signedTextInputs() []struct {
	name  string
	label string
	hash  [32]byte
} {
	return []struct {
		name  string
		label string
		hash  [32]byte
	}{
		{"deposit", EscrowLabelDeposit, seqHash()},
		{"reserve", EscrowLabelReserve, seqHash()},
		{"release", EscrowLabelRelease, seqHash()},
		{"refund", EscrowLabelRefund, seqHash()},
		{"deposit-ff", EscrowLabelDeposit, createFilledBytes32(0xff)},
		{"refund-zero", EscrowLabelRefund, [32]byte{}},
	}
}

// ed25519 group order L.
var ed25519L, _ = new(big.Int).SetString("7237005577332262213973186563042994763544274235525222716252019904098493911093", 10)

// addLToS returns sig with its little-endian S scalar replaced by S+L.
func addLToS(sig []byte) []byte {
	le := sig[32:]
	be := make([]byte, 32)
	for i := range le {
		be[31-i] = le[i]
	}
	s := new(big.Int).SetBytes(be)
	s.Add(s, ed25519L)
	sb := s.FillBytes(make([]byte, 32))
	out := append([]byte{}, sig[:32]...)
	for i := 31; i >= 0; i-- {
		out = append(out, sb[i])
	}
	return out
}

func buildSignedTextFile() signedTextFile {
	priv := ed25519.NewKeyFromSeed(signedTextSeed)
	pub := priv.Public().(ed25519.PublicKey)
	var pk Pubkey
	copy(pk[:], pub)
	f := signedTextFile{
		Comment:   signedTextComment,
		Seed:      hex.EncodeToString(signedTextSeed),
		PublicKey: hex.EncodeToString(pub),
	}
	for _, in := range signedTextInputs() {
		bare := EscrowMessage(EscrowFormBare, in.label, in.hash, pk)
		v1 := EscrowMessage(EscrowFormV1, in.label, in.hash, pk)
		v0 := EscrowMessage(EscrowFormV0, in.label, in.hash, pk)
		f.Vectors = append(f.Vectors, signedTextVector{
			Name:    in.name,
			Label:   in.label,
			Hash:    hex.EncodeToString(in.hash[:]),
			Text:    string(EscrowText(in.label, in.hash)),
			Bare:    hex.EncodeToString(bare),
			V1:      hex.EncodeToString(v1),
			V0:      hex.EncodeToString(v0),
			SigBare: hex.EncodeToString(ed25519.Sign(priv, bare)),
			SigV1:   hex.EncodeToString(ed25519.Sign(priv, v1)),
			SigV0:   hex.EncodeToString(ed25519.Sign(priv, v0)),
		})
	}
	first := f.Vectors[0]
	bare, _ := hex.DecodeString(first.Bare)
	f.NonCanonicalS = []signedTextNegative{{
		Name:      "deposit-bare-s-plus-l",
		Message:   first.Bare,
		Signature: hex.EncodeToString(addLToS(ed25519.Sign(priv, bare))),
	}}
	return f
}

func loadSignedTextFile(t *testing.T) signedTextFile {
	t.Helper()
	raw, err := os.ReadFile(signedTextVectorsPath)
	if err != nil {
		t.Fatalf("read %s: %v", signedTextVectorsPath, err)
	}
	var f signedTextFile
	if err := json.Unmarshal(raw, &f); err != nil {
		t.Fatalf("unmarshal: %v", err)
	}
	return f
}

func mustHex(t *testing.T, s string) []byte {
	t.Helper()
	b, err := hex.DecodeString(s)
	if err != nil {
		t.Fatalf("hex %q: %v", s, err)
	}
	return b
}

func TestSignedTextMatchesFrozenVectors(t *testing.T) {
	f := loadSignedTextFile(t)
	want := buildSignedTextFile()
	if f.PublicKey != want.PublicKey || f.Seed != want.Seed {
		t.Fatalf("seed/publicKey drifted: file %s/%s, derived %s/%s", f.Seed, f.PublicKey, want.Seed, want.PublicKey)
	}
	if len(f.Vectors) != len(want.Vectors) {
		t.Fatalf("file has %d vectors, generator %d", len(f.Vectors), len(want.Vectors))
	}
	pub := ed25519.PublicKey(mustHex(t, f.PublicKey))
	for i, v := range f.Vectors {
		if v != want.Vectors[i] {
			t.Errorf("vector %q differs from the encoder:\nfile %+v\ngot  %+v", v.Name, v, want.Vectors[i])
		}
		if string(mustHex(t, v.Bare)) != v.Text {
			t.Errorf("%s: bare form is not the text", v.Name)
		}
		for _, p := range [][2]string{{v.Bare, v.SigBare}, {v.V1, v.SigV1}, {v.V0, v.SigV0}} {
			if !ed25519.Verify(pub, mustHex(t, p[0]), mustHex(t, p[1])) {
				t.Errorf("%s: signature does not verify", v.Name)
			}
		}
	}
	for _, n := range f.NonCanonicalS {
		sig := mustHex(t, n.Signature)
		if ed25519.Verify(pub, mustHex(t, n.Message), sig) {
			t.Errorf("%s: non-canonical S accepted by a strict verifier", n.Name)
		}
		if !bytes.Equal(addLToS(ed25519.Sign(ed25519.NewKeyFromSeed(signedTextSeed), mustHex(t, n.Message))), sig) {
			t.Errorf("%s: signature is not the canonical one with S+L", n.Name)
		}
	}
}

func TestEscrowTextShape(t *testing.T) {
	for _, in := range signedTextInputs() {
		text := EscrowText(in.label, in.hash)
		if len(text) != len(in.label)+44 {
			t.Errorf("%s: text length %d", in.name, len(text))
		}
		for _, c := range text {
			if c < 0x20 || c > 0x7e || c == '=' {
				t.Errorf("%s: byte %#x outside the allowed set", in.name, c)
			}
		}
	}
}

func TestEscrowMessageEnvelopes(t *testing.T) {
	pk := createFilledPubkey(0x77)
	h := seqHash()
	text := EscrowText(EscrowLabelRelease, h)
	v1 := EscrowMessage(EscrowFormV1, EscrowLabelRelease, h, pk)
	if !bytes.Equal(v1[:16], OffchainSigningDomain[:]) || v1[16] != 1 || v1[17] != 1 ||
		!bytes.Equal(v1[18:50], pk[:]) || !bytes.Equal(v1[50:], text) {
		t.Fatalf("v1 layout: %x", v1)
	}
	v0 := EscrowMessage(EscrowFormV0, EscrowLabelRelease, h, pk)
	if !bytes.Equal(v0[:16], OffchainSigningDomain[:]) || v0[16] != 0 ||
		!bytes.Equal(v0[17:49], make([]byte, 32)) || v0[49] != 0 || v0[50] != 1 ||
		!bytes.Equal(v0[51:83], pk[:]) || int(v0[83])|int(v0[84])<<8 != len(text) ||
		!bytes.Equal(v0[85:], text) {
		t.Fatalf("v0 layout: %x", v0)
	}
}

func TestRegenerateSignedTextVectors(t *testing.T) {
	if os.Getenv("REGEN_SIGNED_TEXT") != "1" {
		t.Skip("set REGEN_SIGNED_TEXT=1 to regenerate the frozen signed-text vectors")
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(buildSignedTextFile()); err != nil {
		t.Fatalf("marshal: %v", err)
	}
	if err := os.MkdirAll(filepath.Dir(signedTextVectorsPath), 0o755); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	if err := os.WriteFile(signedTextVectorsPath, buf.Bytes(), 0o644); err != nil {
		t.Fatalf("write: %v", err)
	}
	t.Logf("wrote %s", signedTextVectorsPath)
}
