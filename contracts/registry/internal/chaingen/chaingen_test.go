// TestChainFilesAreGenerated keeps chains/ equal to what versions.json and the deployments files
// generate, so an address is only ever edited in its deployments file.
func TestChainFilesAreGenerated(t *testing.T) {
	raw, err := os.ReadFile("../../versions.json")
	if err != nil {
		t.Fatal(err)
	}
	spec, err := ParseSpec(raw)
	if err != nil {
		t.Fatal(err)
	}
	want, err := Build(os.DirFS("../../../.."), spec)
	if err != nil {
		t.Fatal(err)
	}
	paths, err := filepath.Glob("../../chains/*.json")
	if err != nil {
		t.Fatal(err)
	}
	const fix = "run `go run ./cmd/gen-chains` in contracts/registry"
	got := map[string]bool{}
	for _, p := range paths {
		name := filepath.Base(p)
		got[name] = true
		b, err := os.ReadFile(p)
		if err != nil {
			t.Fatal(err)
		}
		w, ok := want[name]
		if !ok {
			t.Errorf("chains/%s is not generated by versions.json; %s", name, fix)
			continue
		}
		if !bytes.Equal(b, w) {
			t.Errorf("chains/%s differs from the generated file; %s", name, fix)
		}
	}
	for name := range want {
		if !got[name] {
			t.Errorf("chains/%s is missing; %s", name, fix)
		}
	}
}

const evmSig = `{"eip712Name":"Escrow","eip712Version":"3"}`

func spec(t *testing.T, s string) Spec {
	t.Helper()
	sp, err := ParseSpec([]byte(s))
	if err != nil {
		t.Fatal(err)
	}
	return sp
}

func load(t *testing.T, files map[string][]byte) *registry.Registry {
	t.Helper()
	m := fstest.MapFS{}
	for n, b := range files {
		m["chains/"+n] = &fstest.MapFile{Data: b}
	}
	r, err := registry.LoadFS(m)
	if err != nil {
		t.Fatalf("LoadFS: %v", err)
	}
	return r
}

func TestBuild(t *testing.T) {
	repo := fstest.MapFS{
		"contracts/evm/deployments-v4.json": {Data: []byte(`{
			"$schema": "x",
			"1": {"name": "Ethereum", "mainnet": true, "contracts": {"Escrow": "0xE4", "FulfillmentProxy": "0xF4", "FulfillmentProxyPreview": "0xP4", "Permit2": "0x22"}},
			"11": {"name": "Test", "mainnet": false, "contracts": {"Escrow": "0xT4", "FulfillmentProxy": "0xTF"}}
		}`)},
		"contracts/evm/deployments-v5.json": {Data: []byte(`{"1": {"name": "Ethereum", "mainnet": true, "contracts": {"Escrow": "0xE5", "FulfillmentProxy": "0xF4"}}}`)},
		"contracts/svm/deployments-v4.json": {Data: []byte(`{"Gen": {"name": "Sol", "mainnet": true, "contracts": {"Escrow": "S", "FulfillmentProxy": "SP"}}}`)},
		// Stellar keys its chains by full CAIP-2 id and records an undeployed one as deployed false.
		"contracts/stellar/deploy/deployments-testnet.json": {Data: []byte(`{
			"stellar:testnet": {"name": "Stellar Testnet", "mainnet": false, "deployed": true, "contracts": {"Escrow": "CE", "FulfillmentProxy": "CP"}},
			"stellar:pubnet": {"name": "Stellar", "mainnet": true, "deployed": false, "contracts": {"Escrow": "CX", "FulfillmentProxy": "CY"}}
		}`)},
	}
	files, err := Build(repo, spec(t, `{"versions": [
		{"id": "v4", "source": "contracts/evm/deployments-v4.json", "signature": `+evmSig+`},
		{"id": "v5", "source": "contracts/evm/deployments-v5.json", "signature": `+evmSig+`},
		{"id": "v4", "source": "contracts/svm/deployments-v4.json", "signature": {"svmDomainVersion": 5}},
		{"id": "v4", "source": "contracts/stellar/deploy/deployments-testnet.json", "signature": {"stellarDomainVersion": 2}}
	], "unrecordedFulfillmentProxies": [{"address": "0xOLD", "version": "v4", "chains": ["eip155:11"], "reason": "old"}]}`))
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	if got := strings.Join(names, ","); got != "eip155_1.json,eip155_11.json,solana_Gen.json,stellar_testnet.json" {
		t.Fatalf("files %s", got)
	}
	r := load(t, files)
	c, _ := r.Chain("eip155:1")
	if c.Name != "Ethereum" || !c.Mainnet || len(c.Versions) != 2 || c.Versions[0].ID != "v4" || c.Versions[1].ID != "v5" {
		t.Fatalf("eip155:1 = %+v", c)
	}
	v4 := c.Versions[0]
	if v4.Escrow != "0xE4" || v4.Permit2 != "0x22" || strings.Join(v4.FulfillmentProxies, ",") != "0xF4,0xP4" || v4.Source != "contracts/evm/deployments-v4.json" {
		t.Errorf("v4 = %+v", v4)
	}
	if v5 := c.Versions[1]; v5.Permit2 != "" || strings.Join(v5.FulfillmentProxies, ",") != "0xF4" {
		t.Errorf("v5 = %+v", v5)
	}
	test, _ := r.Version("eip155:11", "v4")
	if strings.Join(test.FulfillmentProxies, ",") != "0xTF,0xOLD" || test.UnrecordedFulfillmentProxies["0xOLD"] != "old" {
		t.Errorf("unrecorded proxy not appended: %+v", test)
	}
	if sol, _ := r.Version("solana:Gen", "v4"); sol.Signature.SVMDomainVersion != 5 || sol.Escrow != "S" {
		t.Errorf("solana = %+v", sol)
	}
	if xlm, ok := r.Version("stellar:testnet", "v4"); !ok || xlm.Signature.StellarDomainVersion != 2 || xlm.Escrow != "CE" {
		t.Errorf("stellar = %+v", xlm)
	}
}

func TestBuildRefuses(t *testing.T) {
	good := `{"1": {"name": "Ethereum", "mainnet": true, "contracts": {"Escrow": "0xE", "FulfillmentProxy": "0xF"}}}`
	cases := []struct {
		name, v4, v5, spec, want string
	}{
		{"unknown VM", good, good, `{"versions": [{"id": "v4", "source": "contracts/xvm/d.json", "signature": ` + evmSig + `}]}`, "unknown VM"},
		{"missing source", good, good, `{"versions": [{"id": "v4", "source": "contracts/evm/none.json", "signature": ` + evmSig + `}]}`, "none.json"},
		{"missing proxy", `{"1": {"name": "Ethereum", "mainnet": true, "contracts": {"Escrow": "0xE"}}}`, good, `{"versions": [{"id": "v4", "source": "contracts/evm/v4.json", "signature": ` + evmSig + `}]}`, "no Escrow or FulfillmentProxy"},
		{"empty escrow", `{"1": {"name": "Ethereum", "mainnet": true, "contracts": {"Escrow": "", "FulfillmentProxy": "0xF"}}}`, good, `{"versions": [{"id": "v4", "source": "contracts/evm/v4.json", "signature": ` + evmSig + `}]}`, "no Escrow or FulfillmentProxy"},
		{"no chain entries", `{"$schema": "x"}`, good, `{"versions": [{"id": "v4", "source": "contracts/evm/v4.json", "signature": ` + evmSig + `}]}`, "no chain entries"},
		{"names disagree", good, strings.Replace(good, "Ethereum", "Other", 1), `{"versions": [{"id": "v4", "source": "contracts/evm/v4.json", "signature": ` + evmSig + `}, {"id": "v5", "source": "contracts/evm/v5.json", "signature": ` + evmSig + `}]}`, "another deployments file"},
		{"unrecorded on a missing version", good, good, `{"versions": [{"id": "v4", "source": "contracts/evm/v4.json", "signature": ` + evmSig + `}], "unrecordedFulfillmentProxies": [{"address": "0xO", "version": "v9", "chains": ["eip155:1"], "reason": "r"}]}`, "has no version v9"},
		{"unrecorded on a missing chain", good, good, `{"versions": [{"id": "v4", "source": "contracts/evm/v4.json", "signature": ` + evmSig + `}], "unrecordedFulfillmentProxies": [{"address": "0xO", "version": "v4", "chains": ["eip155:2"], "reason": "r"}]}`, "has no version v4"},
		{"unrecorded already recorded", good, good, `{"versions": [{"id": "v4", "source": "contracts/evm/v4.json", "signature": ` + evmSig + `}], "unrecordedFulfillmentProxies": [{"address": "0xf", "version": "v4", "chains": ["eip155:1"], "reason": "r"}]}`, "already lists it"},
		{"unrecorded without a reason", good, good, `{"versions": [{"id": "v4", "source": "contracts/evm/v4.json", "signature": ` + evmSig + `}], "unrecordedFulfillmentProxies": [{"address": "0xO", "version": "v4", "chains": ["eip155:1"]}]}`, "required"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			repo := fstest.MapFS{"contracts/evm/v4.json": {Data: []byte(tc.v4)}, "contracts/evm/v5.json": {Data: []byte(tc.v5)}}
			_, err := Build(repo, spec(t, tc.spec))
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("Build() = %v, want error containing %q", err, tc.want)
			}
		})
	}
	if _, err := ParseSpec([]byte(`{"versions": [], "extra": 1}`)); err == nil {
		t.Error("ParseSpec accepted an unknown field")
	}
}
